create or replace function public.make_order_number()
returns text
language plpgsql
volatile
set search_path = public, pg_temp
as $$
declare
  v_order_number text;
begin
  loop
    v_order_number := 'SKQ-' || upper(substr(encode(gen_random_bytes(6), 'hex'), 1, 10));
    exit when not exists (select 1 from public.orders where order_number = v_order_number);
  end loop;
  return v_order_number;
end;
$$;

create or replace function public.hash_collection_token(p_token text)
returns text
language sql
immutable
set search_path = public, pg_temp
as $$
  select encode(digest(p_token, 'sha256'), 'hex');
$$;

create or replace function public.active_reserved_quantity(p_menu_item_id uuid)
returns integer
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce(sum(quantity), 0)::integer
  from public.inventory_reservations
  where menu_item_id = p_menu_item_id
    and status = 'ACTIVE'
    and expires_at > now();
$$;

create or replace function public.create_collection_code(p_order_id uuid)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_token text;
begin
  v_token := encode(gen_random_bytes(32), 'base64url');
  insert into public.collection_codes(order_id, token_hash)
  values (p_order_id, public.hash_collection_token(v_token));
  return v_token;
end;
$$;

create or replace function public.create_cash_order(p_shop_id uuid, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid := gen_random_uuid();
  v_order_number text := public.make_order_number();
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_menu public.menu_items%rowtype;
  v_qty integer;
  v_uni uuid;
  v_cafe uuid;
  v_token text;
begin
  if v_user_id is null or not public.has_role(v_user_id, 'customer') then
    raise exception 'Only authenticated customers can create orders';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Order must contain at least one item';
  end if;

  select c.university_id, s.cafeteria_id into v_uni, v_cafe
  from public.shops s
  join public.cafeterias c on c.id = s.cafeteria_id
  join public.universities u on u.id = c.university_id
  where s.id = p_shop_id and s.is_active and s.approval_status = 'APPROVED'
    and c.is_active and c.approval_status = 'APPROVED' and u.is_active;
  if v_uni is null then raise exception 'Shop is not orderable'; end if;

  insert into public.orders(id, order_number, customer_id, university_id, cafeteria_id, shop_id, status, payment_method, total_amount)
  values (v_order_id, v_order_number, v_user_id, v_uni, v_cafe, p_shop_id, 'PLACED', 'CASH', 0);

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_menu from public.menu_items where id = (v_item->>'menu_item_id')::uuid and shop_id = p_shop_id for update;
    if not found or not v_menu.is_active or not v_menu.is_manually_available then raise exception 'Menu item is unavailable'; end if;
    if v_qty is null or v_qty <= 0 or v_qty > v_menu.max_quantity_per_order then raise exception 'Invalid item quantity'; end if;
    if v_menu.stock_quantity - public.active_reserved_quantity(v_menu.id) < v_qty then raise exception 'Insufficient stock'; end if;
    update public.menu_items set stock_quantity = stock_quantity - v_qty where id = v_menu.id;
    insert into public.order_items(order_id, menu_item_id, item_name_snapshot, quantity, unit_price_snapshot, line_total_snapshot)
    values (v_order_id, v_menu.id, v_menu.name, v_qty, v_menu.price, v_qty * v_menu.price);
    v_total := v_total + (v_qty * v_menu.price);
  end loop;

  update public.orders set total_amount = v_total where id = v_order_id;
  insert into public.payment_attempts(order_id, method, status, amount, transaction_ref, paid_at)
  values (v_order_id, 'CASH', 'PAID', v_total, 'CASH-' || v_order_number, now());
  insert into public.order_status_events(order_id, previous_status, new_status, actor_user_id)
  values (v_order_id, null, 'PLACED', v_user_id);
  v_token := public.create_collection_code(v_order_id);
  return jsonb_build_object('order_id', v_order_id, 'order_number', v_order_number, 'collection_token', v_token);
end;
$$;

create or replace function public.create_online_checkout(p_shop_id uuid, p_items jsonb, p_reservation_minutes integer default 15)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid := gen_random_uuid();
  v_payment_id uuid := gen_random_uuid();
  v_order_number text := public.make_order_number();
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_menu public.menu_items%rowtype;
  v_qty integer;
  v_uni uuid;
  v_cafe uuid;
  v_transaction_ref text := 'SSL-' || upper(encode(gen_random_bytes(12), 'hex'));
  v_expires_at timestamptz := now() + make_interval(mins => greatest(p_reservation_minutes, 1));
begin
  if v_user_id is null or not public.has_role(v_user_id, 'customer') then raise exception 'Only authenticated customers can create checkouts'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Checkout must contain at least one item'; end if;

  select c.university_id, s.cafeteria_id into v_uni, v_cafe
  from public.shops s join public.cafeterias c on c.id = s.cafeteria_id join public.universities u on u.id = c.university_id
  where s.id = p_shop_id and s.is_active and s.approval_status = 'APPROVED' and c.is_active and c.approval_status = 'APPROVED' and u.is_active;
  if v_uni is null then raise exception 'Shop is not orderable'; end if;

  insert into public.orders(id, order_number, customer_id, university_id, cafeteria_id, shop_id, status, payment_method, total_amount)
  values (v_order_id, v_order_number, v_user_id, v_uni, v_cafe, p_shop_id, 'PAYMENT_PENDING', 'ONLINE', 0);

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_menu from public.menu_items where id = (v_item->>'menu_item_id')::uuid and shop_id = p_shop_id for update;
    if not found or not v_menu.is_active or not v_menu.is_manually_available then raise exception 'Menu item is unavailable'; end if;
    if v_qty is null or v_qty <= 0 or v_qty > v_menu.max_quantity_per_order then raise exception 'Invalid item quantity'; end if;
    if v_menu.stock_quantity - public.active_reserved_quantity(v_menu.id) < v_qty then raise exception 'Insufficient stock'; end if;
    insert into public.order_items(order_id, menu_item_id, item_name_snapshot, quantity, unit_price_snapshot, line_total_snapshot)
    values (v_order_id, v_menu.id, v_menu.name, v_qty, v_menu.price, v_qty * v_menu.price);
    insert into public.inventory_reservations(menu_item_id, order_id, payment_attempt_id, quantity, status, expires_at)
    values (v_menu.id, v_order_id, v_payment_id, v_qty, 'ACTIVE', v_expires_at);
    v_total := v_total + (v_qty * v_menu.price);
  end loop;

  update public.orders set total_amount = v_total where id = v_order_id;
  insert into public.payment_attempts(id, order_id, method, provider, status, amount, transaction_ref)
  values (v_payment_id, v_order_id, 'ONLINE', 'SSLCOMMERZ', 'PENDING', v_total, v_transaction_ref);
  insert into public.order_status_events(order_id, previous_status, new_status, actor_user_id)
  values (v_order_id, null, 'PAYMENT_PENDING', v_user_id);
  return jsonb_build_object('order_id', v_order_id, 'order_number', v_order_number, 'payment_attempt_id', v_payment_id, 'transaction_ref', v_transaction_ref, 'amount', v_total, 'expires_at', v_expires_at);
end;
$$;

create or replace function public.finalize_successful_online_payment(p_transaction_ref text, p_amount numeric, p_currency char(3), p_gateway_transaction_id text, p_gateway_metadata jsonb default '{}'::jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_payment public.payment_attempts%rowtype;
  v_order public.orders%rowtype;
  v_res public.inventory_reservations%rowtype;
  v_token text;
begin
  select * into v_payment from public.payment_attempts where transaction_ref = p_transaction_ref for update;
  if not found then raise exception 'Payment attempt not found'; end if;
  select * into v_order from public.orders where id = v_payment.order_id for update;
  if v_payment.status = 'PAID' then
    return jsonb_build_object('order_id', v_order.id, 'order_number', v_order.order_number, 'already_finalized', true);
  end if;
  if v_payment.method <> 'ONLINE' or v_payment.provider <> 'SSLCOMMERZ' or v_payment.status <> 'PENDING' then raise exception 'Payment attempt is not finalizable'; end if;
  if v_payment.amount <> p_amount or v_payment.currency <> p_currency then raise exception 'Payment amount or currency mismatch'; end if;
  if v_order.status <> 'PAYMENT_PENDING' then raise exception 'Order is not payment pending'; end if;

  for v_res in select * from public.inventory_reservations where payment_attempt_id = v_payment.id and order_id = v_order.id for update loop
    if v_res.status <> 'ACTIVE' or v_res.expires_at <= now() then raise exception 'Reservation is not active'; end if;
    update public.menu_items set stock_quantity = stock_quantity - v_res.quantity where id = v_res.menu_item_id and stock_quantity >= v_res.quantity;
    if not found then raise exception 'Insufficient stock during finalization'; end if;
    update public.inventory_reservations set status = 'CONSUMED', consumed_at = now() where id = v_res.id;
  end loop;

  update public.payment_attempts set status = 'PAID', paid_at = now(), gateway_transaction_id = p_gateway_transaction_id, gateway_metadata = p_gateway_metadata where id = v_payment.id;
  update public.orders set status = 'PLACED' where id = v_order.id;
  insert into public.order_status_events(order_id, previous_status, new_status, actor_user_id, metadata)
  values (v_order.id, 'PAYMENT_PENDING', 'PLACED', null, jsonb_build_object('payment_attempt_id', v_payment.id));
  v_token := public.create_collection_code(v_order.id);
  return jsonb_build_object('order_id', v_order.id, 'order_number', v_order.order_number, 'collection_token', v_token, 'already_finalized', false);
end;
$$;

create or replace function public.release_expired_reservations(p_payment_attempt_id uuid default null)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_count integer;
begin
  update public.inventory_reservations ir
  set status = 'EXPIRED', expired_at = now()
  where ir.status = 'ACTIVE'
    and (p_payment_attempt_id is null or ir.payment_attempt_id = p_payment_attempt_id)
    and ir.expires_at <= now();
  get diagnostics v_count = row_count;

  update public.payment_attempts pa
  set status = 'EXPIRED', expired_at = now()
  where pa.status = 'PENDING'
    and exists (select 1 from public.inventory_reservations ir where ir.payment_attempt_id = pa.id and ir.status = 'EXPIRED')
    and not exists (select 1 from public.inventory_reservations ir where ir.payment_attempt_id = pa.id and ir.status = 'ACTIVE');
  return v_count;
end;
$$;

create or replace function public.cancel_order(p_order_id uuid, p_reason text, p_restore_inventory boolean default false)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_order public.orders%rowtype;
  v_item record;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if not public.is_active_shop_staff(v_user_id, v_order.shop_id) then raise exception 'Not authorized for this shop'; end if;
  if btrim(coalesce(p_reason, '')) = '' then raise exception 'Cancellation reason is required'; end if;
  if v_order.status not in ('PLACED', 'PREPARING') then raise exception 'Order cannot be cancelled from current status'; end if;

  if p_restore_inventory then
    for v_item in select menu_item_id, quantity from public.order_items where order_id = p_order_id loop
      update public.menu_items set stock_quantity = stock_quantity + v_item.quantity where id = v_item.menu_item_id;
    end loop;
  end if;

  update public.orders
  set status = 'CANCELLED', cancelled_at = now(), cancelled_by = v_user_id, cancellation_reason = p_reason, inventory_restored = p_restore_inventory
  where id = p_order_id;
  insert into public.order_status_events(order_id, previous_status, new_status, actor_user_id, reason, metadata)
  values (p_order_id, v_order.status, 'CANCELLED', v_user_id, p_reason, jsonb_build_object('inventory_restored', p_restore_inventory));
  update public.payment_attempts
  set refund_status = case when method = 'ONLINE' and status = 'PAID' then 'PENDING' else refund_status end,
      status = case when status = 'PENDING' then 'CANCELLED' else status end,
      cancelled_at = case when status = 'PENDING' then now() else cancelled_at end
  where order_id = p_order_id;
  return jsonb_build_object('order_id', p_order_id, 'status', 'CANCELLED');
end;
$$;

create or replace function public.validate_collection_qr(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_hash text := public.hash_collection_token(p_token);
  v_code public.collection_codes%rowtype;
  v_order public.orders%rowtype;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  select * into v_code from public.collection_codes where token_hash = v_hash for update;
  if not found then raise exception 'Invalid collection code'; end if;
  if v_code.used_at is not null then raise exception 'Collection code already used'; end if;
  if v_code.expires_at is not null and v_code.expires_at <= now() then raise exception 'Collection code expired'; end if;
  select * into v_order from public.orders where id = v_code.order_id for update;
  if v_order.status <> 'READY' then raise exception 'Order is not ready for collection'; end if;
  if not public.is_active_shop_staff(v_user_id, v_order.shop_id) then raise exception 'Not authorized for this shop'; end if;

  update public.orders set status = 'COLLECTED', collected_at = now(), collected_by = v_user_id where id = v_order.id;
  update public.collection_codes set used_at = now(), validated_by = v_user_id where id = v_code.id;
  insert into public.order_status_events(order_id, previous_status, new_status, actor_user_id)
  values (v_order.id, 'READY', 'COLLECTED', v_user_id);
  return jsonb_build_object('order_id', v_order.id, 'order_number', v_order.order_number, 'status', 'COLLECTED');
end;
$$;

create or replace function public.update_order_status(p_order_id uuid, p_new_status public.order_status)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_order public.orders%rowtype;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if not public.is_active_shop_staff(v_user_id, v_order.shop_id) then raise exception 'Not authorized for this shop'; end if;
  if not ((v_order.status = 'PLACED' and p_new_status = 'PREPARING') or (v_order.status = 'PREPARING' and p_new_status = 'READY')) then
    raise exception 'Invalid order status transition';
  end if;
  update public.orders set status = p_new_status where id = p_order_id;
  insert into public.order_status_events(order_id, previous_status, new_status, actor_user_id)
  values (p_order_id, v_order.status, p_new_status, v_user_id);
  return jsonb_build_object('order_id', p_order_id, 'status', p_new_status);
end;
$$;

