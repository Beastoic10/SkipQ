  refund_reference text,
  refund_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint payment_attempts_amount_non_negative check (amount >= 0),
  constraint payment_attempts_online_provider check ((method = 'ONLINE' and provider = 'SSLCOMMERZ') or (method = 'CASH' and provider is null)),
