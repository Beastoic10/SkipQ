create or replace function public.has_role(p_user_id uuid, p_role public.role_name)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.user_roles ur
    join public.roles r on r.id = ur.role_id
    join public.profiles p on p.id = ur.user_id
    where ur.user_id = p_user_id
      and r.name = p_role
      and ur.is_active
      and p.is_active
  );
$$;

