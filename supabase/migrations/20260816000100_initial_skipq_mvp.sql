create extension if not exists pgcrypto;

create type public.role_name as enum ('customer', 'shop_staff', 'admin');
create type public.approval_status as enum ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED');
create type public.order_status as enum ('PAYMENT_PENDING', 'PLACED', 'PREPARING', 'READY', 'COLLECTED', 'CANCELLED');
create type public.payment_method as enum ('CASH', 'ONLINE');
create type public.payment_provider as enum ('SSLCOMMERZ');
create type public.payment_status as enum ('PENDING', 'PAID', 'FAILED', 'CANCELLED', 'EXPIRED', 'REFUND_PENDING', 'REFUNDED');
create type public.refund_status as enum ('NOT_REQUIRED', 'PENDING', 'REFUNDED', 'FAILED');
create type public.reservation_status as enum ('ACTIVE', 'CONSUMED', 'RELEASED', 'EXPIRED');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  phone text unique,
  avatar_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_display_name_not_blank check (display_name is null or btrim(display_name) <> ''),
  constraint profiles_phone_not_blank check (phone is null or btrim(phone) <> '')
);

create table public.roles (
  id smallint generated by default as identity primary key,
  name public.role_name not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  role_id smallint not null references public.roles(id) on delete restrict,
  is_active boolean not null default true,
  assigned_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.universities (
