create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_id uuid not null references public.profiles(id) on delete restrict,
  university_id uuid not null references public.universities(id) on delete restrict,
  cafeteria_id uuid not null references public.cafeterias(id) on delete restrict,
  shop_id uuid not null references public.shops(id) on delete restrict,
  status public.order_status not null,
  payment_method public.payment_method not null,
  total_amount numeric(12,2) not null,
  currency char(3) not null default 'BDT',
  cancelled_at timestamptz,
  cancelled_by uuid references public.profiles(id) on delete set null,
  cancellation_reason text,
  inventory_restored boolean not null default false,
  collected_at timestamptz,
  collected_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_total_non_negative check (total_amount >= 0),
  constraint orders_cancelled_metadata check (
    (status <> 'CANCELLED') or (cancelled_at is not null and cancelled_by is not null and btrim(coalesce(cancellation_reason, '')) <> '')
  ),
  constraint orders_collected_metadata check (
    (status <> 'COLLECTED') or (collected_at is not null and collected_by is not null)
  )
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  menu_item_id uuid not null references public.menu_items(id) on delete restrict,
  item_name_snapshot text not null,
  quantity integer not null,
  unit_price_snapshot numeric(12,2) not null,
  line_total_snapshot numeric(12,2) not null,
  created_at timestamptz not null default now(),
  constraint order_items_name_snapshot_not_blank check (btrim(item_name_snapshot) <> ''),
  constraint order_items_quantity_positive check (quantity > 0),
  constraint order_items_unit_price_non_negative check (unit_price_snapshot >= 0),
  constraint order_items_line_total_valid check (line_total_snapshot = quantity * unit_price_snapshot)
);

create table public.order_status_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  previous_status public.order_status,
  new_status public.order_status not null,
  actor_user_id uuid references public.profiles(id) on delete set null,
  reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint order_status_events_reason_for_cancel check (new_status <> 'CANCELLED' or btrim(coalesce(reason, '')) <> '')
);

create table public.payment_attempts (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  method public.payment_method not null,
  provider public.payment_provider,
  provider_channel text,
  status public.payment_status not null default 'PENDING',
  amount numeric(12,2) not null,
  currency char(3) not null default 'BDT',
  transaction_ref text not null unique,
  gateway_session_id text unique,
  gateway_transaction_id text unique,
  gateway_metadata jsonb not null default '{}'::jsonb,
  paid_at timestamptz,
  failed_at timestamptz,
  cancelled_at timestamptz,
  expired_at timestamptz,
